const cache = new Map();
export function icon(name, cls = '') {
  const k = name + '|' + cls;
  if (cache.has(k)) return cache.get(k);
  const rows = (I[name] || I.skull).trim().split('\n').map((r) => r.trim());
  let a = '', b = '';
  rows.forEach((r, y) => [...r].forEach((ch, x) => {
    if (ch === '#') a += `M${x} ${y}h1v1h-1z`;
    else if (ch === '+') b += `M${x} ${y}h1v1h-1z`;
  }));
  const svg = `<svg class="px ${cls}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true"><path d="${b}" fill="currentColor" opacity=".45"/><path d="${a}" fill="currentColor"/></svg>`;
  cache.set(k, svg);
  return svg;
}
